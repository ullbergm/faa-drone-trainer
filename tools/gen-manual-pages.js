#!/usr/bin/env node
/* Regenerates data/manual-pages.js from local copies of the two FAA PDFs the
 * bank cites: the Remote Pilot Study Guide (FAA-G-8082-22) and AC 107-2A.
 *
 * The study guide prints a plain page number in its footer; the AC prints
 * chapter-relative labels ("5-14", "A-1"). A PDF viewer's #page= fragment
 * wants the physical page index, so the app needs a map between the two.
 * This walks each PDF, reads the label out of each page's footer, and writes
 * the result out as a plain script the page can load.
 *
 * Usage: node tools/gen-manual-pages.js [study-guide.pdf] [ac-107-2a.pdf]
 * Needs pdftotext (poppler-utils) on PATH. The PDFs are not in the repo;
 * grab them from the FAA links in the README first. */
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const sgPdf = process.argv[2] || path.join(__dirname, '..', 'remote_pilot_study_guide.pdf');
const acPdf = process.argv[3] || path.join(__dirname, '..', 'ac_107-2a.pdf');
for (const pdf of [sgPdf, acPdf]) {
  if (!fs.existsSync(pdf)) {
    console.error(`${pdf} not found. Download the FAA PDFs first, or pass their paths.`);
    process.exit(1);
  }
}

function pagesOf(pdf) {
  const text = execFileSync('pdftotext', ['-layout', pdf, '-'], { maxBuffer: 64 * 1024 * 1024 }).toString();
  return text.split('\f');
}

// Study guide: footer reads "Remote Pilot – Small Unmanned Aircraft Systems
// Study Guide        17". Front matter uses roman numerals, which the bank
// never cites, so only plain numbers are kept.
const sg = {};
pagesOf(sgPdf).forEach((page, i) => {
  for (const line of page.split('\n').slice(-8)) {
    const m = /Study Guide\s+(\d+)\s*$/.exec(line.trimEnd());
    if (m && !(m[1] in sg)) sg[m[1]] = i + 1;
  }
});

// AC 107-2A: the chapter-relative label sits alone on the last line of the
// body ("5-14", "A-1"). Roman-numbered front matter is skipped the same way.
const ac = {};
pagesOf(acPdf).forEach((page, i) => {
  const lines = page.split('\n').map(l => l.trim()).filter(Boolean);
  const last = lines[lines.length - 1] || '';
  const m = /^([0-9A-Z]-?\d+-\d+|[0-9A-Z]+-\d+)$/.exec(last);
  if (m && !(m[1] in ac)) ac[m[1]] = i + 1;
});

const fmt = map => Object.keys(map).map(l => `    '${l}': ${map[l]},`).join('\n');
const out = `/* Generated by tools/gen-manual-pages.js. Do not edit by hand.
   Maps each manual's printed page labels to physical page numbers in the FAA
   PDFs, so a citation can deep link with #page=. \`sg\` is the Remote Pilot
   Study Guide (FAA-G-8082-22, plain page numbers); \`ac\` is AC 107-2A
   (chapter-relative labels like "5-14"). Regenerate whenever the FAA
   publishes a revision. */
const MANUAL_PAGES = {
  sg: {
${fmt(sg)}
  },
  ac: {
${fmt(ac)}
  },
};
`;
const dest = path.join(__dirname, '..', 'data', 'manual-pages.js');
fs.writeFileSync(dest, out);
console.log(`wrote ${Object.keys(sg).length} study-guide + ${Object.keys(ac).length} AC page labels to ${path.relative(process.cwd(), dest)}`);
